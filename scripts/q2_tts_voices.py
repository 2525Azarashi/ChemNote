#!/usr/bin/env python3
"""
===================================================================
第2問 TTS の声の割り当て（生成の再現性を保つための固定表）
===================================================================

★このファイルは「誰にどの声を使ったか」の記録である。★

-------------------------------------------------------------------
■ なぜ声を固定するのか
-------------------------------------------------------------------
TTS は同じ台本を渡しても、呼び出しごとに声が変わることがある。
第2問は38問あるので、声が揺れると次のような事故が起きる。

  ・第1セット問1 は落ち着いた女性、問2 は甲高い女性、というふうに
    同じ「女性」役の声が問ごとに変わり、生徒が別人だと誤解する
  ・設問文（Question. …）を読むナレーターの声が対話の話者と
    かぶってしまい、どこから設問なのか聞き分けられなくなる
  ・生成に失敗した1問だけを録り直したとき、その問だけ声が浮く

そこで「役割 → 声」の対応をこのファイルに固定し、
生成のたびに同じ声を指定する。

-------------------------------------------------------------------
■ 実際に使った声（1問目で品質確認済み）
-------------------------------------------------------------------
el2_set1_q1 を生成して内容を検証したところ、

  Speaker 1（女性・店員） = Adeline
  Speaker 2（男性・客）   = Mark
  Speaker 3（ナレーター） = Sam

の組み合わせで、
  ・5行すべてが台本どおりに読まれている
  ・3声が性別と音色で明確に区別できる
  ・BGM・効果音・ノイズ・途切れが無い
  ・設問文の前に明確な間がある
  ・試験音源として適切な速度
が確認できた。この組み合わせを全38問で使う。

-------------------------------------------------------------------
■ ★既知の欠陥：ナレーターの声が男性話者とかぶる★
-------------------------------------------------------------------
対話は必ず「男女ペア」なので、ナレーターを男女どちらにしても
片方の話者と性別がかぶる。当初は

  ・ナレーターは対話の2人とは音色がはっきり違う声にする
  ・設問文の前に間を置き、読み方をフォーマルにする

の2点で区別できると考え、Sam（男性）を採用した。

ところが生成後に4本を聞き取り検証したところ、

  el2_set1_q1（女性が先に話す）… ナレーターは2人と区別できる
  el2_set2_q1 / el2_set2_q3 / el2_set3_q2（男性が先に話す）
    … 「ナレーターは男性話者とまったく同じ声に聞こえる」と判定された

つまり Sam と Mark の音色が近く、男性が対話に出る問では
ナレーターが聞き分けられない。全38問のうち男性が出るのは全問なので、
これは全問に影響する。

【影響の程度】
  内容の正確さ・音質・速度・設問前の間はすべて問題なし。
  設問文は必ず "Question." で始まり、その前に間があるので、
  どこから設問かは判別できる。よって実用は可能。
  ただし本番の音源はナレーターが明確に別人なので、そこは劣る。

【直し方（クレジット回復後）】
  VOICE_NARRATOR を Mark と音色が離れた声へ差し替え、
  同じ4本を録り直して再検証する。候補は
    ・女性のナレーター（女性話者とかぶるが、Sam より差が出る可能性）
    ・英国系アクセントなど、音色が明確に違う男性
  差し替えたら必ず analyze_media_content で
  「ナレーターが対話の2人と区別できるか」を再確認すること。
  声を変えたら全38問を録り直す（1問だけ変えると声が浮く）。

-------------------------------------------------------------------
■ 話者記号と役割
-------------------------------------------------------------------
PDF の話者記号は W/M/K/S/F/D。基本は W=女性・M=男性 だが、
一部の問では M が「母親」を指す。したがって記号ではなく
manifest.json の voiceMap（日本語の役割）から性別を決める。

  女性側の声 = 女性 / 母親 / 娘 / 女子
  男性側の声 = 男性 / 父親 / 息子 / 男子

判定できない役割が出たら例外を投げる。黙って男性にすると
「母親が男の声で話す」ような嘘の音源ができてしまうため。
===================================================================
"""

from __future__ import annotations

# 実測で品質を確認した声（el2_set1_q1 で検証済み）
VOICE_FEMALE = 'Adeline'
VOICE_MALE = 'Mark'

# ★★★ 現在の音源の状態（2026-08-31 時点）★★★
#
#   batch01 の6問（el2_set1_q1/q2/q3, el2_set2_q1/q3, el2_set3_q2）
#     … ★Daniel で録音済み・検証済み★
#   batch02 の6問（el2_set4_q1/q2/q3, el2_set5_q2/q3, el2_set6_q1）
#     … ★Daniel で録音済み・検証済み★
#   batch03〜07 の26問
#     … 未録音（生成クレジットが尽きたため）
#
# → 38問中 12問 完了。表（このファイル）と音源の食い違いは無い。
# 残り26問を録るときも、この表のとおり Daniel を指定すること。
# 手順は本ファイル末尾の「■ 残り作業」に書いてある。
#
# -------------------------------------------------------------------
# ★★★ 話者分離の検証結果（Daniel 版・実測）★★★
# -------------------------------------------------------------------
# ナレーターが対話の話者と混同されていないかは「聞いた印象」では
# 判定がぶれる。実際、聞き取り検証ツールは Daniel 版に対して
# 「ナレーターが女性役と同じ声に聞こえる」と報告したが、
# ★同じ応答の中で「音声ファイルが渡されていない」とも述べており、
#   判定の根拠が無かった。★
#
# そこで librosa で機械的に測る方式にした。
# 検証は ★scripts/verify_q2_tts_speakers.py★ で行う。
#
#   python3 scripts/verify_q2_tts_speakers.py \
#       .tmpwork/tts/batch02.mp3 \
#       .tmpwork/tts/batch02_words.json \
#       scripts/data/q2_tts_batches/batch02.json
#
# 【判定方法：一つ抜き最近傍法】
#   区間を1つ抜き、残りから作った3役の重心のうちどれに最も近いかを当てる。
#   本当に3人の声なら、抜いた区間は自分の役に戻る。
#   ナレーターの正答率が 80% 以上で合格（でたらめなら約33%）。
#
# 【実測結果】
#   batch01 … ナレーター 7/7 = 100%   全体 26/29 = 89.7%
#             F0: ナレーター 173.7 / 女性役 220.9 / 男性役 107.0 Hz
#   batch02 … ナレーター 7/7 = 100%   全体 26/29 = 89.7%
#             F0: ナレーター 205.2 / 女性役 197.5 / 男性役 122.3 Hz
#
#   → ★どちらもナレーターは3人目として完全に分離できている。★
#
# 【★声の高さだけで判断してはいけない（batch02 が実例）★】
#   batch02 はナレーター 205.2Hz と女性役 197.5Hz が
#   わずか 7.7Hz しか離れていない。高さだけ見ると「同じ声」に見える。
#   しかし声質（MFCC）では 7/7 = 100% 分離できていた。
#   高さが近くても音色が違えば聞き分けられる、ということ。
#
# 【★以前使っていた基準は捨てた（理由を残す）★】
#   古い基準：「ナレーター内の類似度 − ナレーターと相手の類似度 ≧ 0.03」
#   これは batch02 で +0.0096 しか出ず「同一人物の疑い」と誤判定した。
#   原因は「ナレーター内の類似度」が区間の長さに引っぱられること。
#   batch02 のナレーターは "Number one." のような1秒前後の区間が多く、
#   ナレーター内が 0.9604 まで下がっていた（batch01 は 0.9961）。
#   つまりこの基準では「声が似ている」のか「区間が短い」のか
#   区別できない。だから一つ抜き最近傍法に変えた。
#
# -------------------------------------------------------------------
# ★ナレーターは Sam → Daniel へ差し替えた（2026-08-30）★
#
# 【なぜ差し替えたか】
# 上の「既知の欠陥」に書いたとおり、Sam は Mark と音色が近く、
# 男性が対話に出る問（＝全38問）でナレーターが聞き分けられなかった。
# 聞き取り検証でも次のように明確に判定された。
#
#   「the narrator sounds like the EXACT SAME PERSON as the male
#     speaker in the dialogue. They share the same voice model,
#     pitch, and timbre.」
#   「Must be re-recorded.」
#
# 生徒から見ると「対話していた男性が、急に自分へ質問してきた」
# ように聞こえる。本番の試験音源はナレーターが明確に別人なので、
# これは音源の作りとして誤りである。
#
# 【なぜ「今」直すのか（費用の判断）】
# まとめ録り（gen_q2_tts_batches.py）に切り替えたため、38問の
# 録音に必要な生成の呼び出しは7回で済む。
#
#   ここで直す   … 残り6本 ＋ batch01 の録り直し1本 = 7回
#   後で直す     … 残り6本を録ってから、38問を全部録り直す = 6 + 7 = 13回
#
# つまり今直せば追加は1回だけで済む。逆に「とりあえず全部録って
# あとで直す」と、欠陥を承知で録った38問を捨てることになる。
# 1問ずつ録っていた頃は「録り直し＝38回」だったので後回しにする
# 判断もあり得たが、まとめ録りにした今は先に直すのが明らかに安い。
#
# 【なぜ Daniel を選んだか】
# ・英国系の男性で、米国英語の Mark とアクセントから違う。
#   性別ではなくアクセントで差を付けるのが要点。
# ・女性ナレーターにする案もあったが、対話の女性（Adeline）と
#   かぶるだけで問題が移動するにすぎない。対話は必ず男女ペアなので、
#   性別を変えても必ずどちらかとかぶる。だから「性別が同じでも
#   音色とアクセントが明確に違う声」を選ぶのが正しい。
# ・落ち着いた報道系の声質で、試験のナレーションに向く。
#
# 【差し替えたら必ずやること】
# ・38問すべてを録り直す（1問だけ変えるとその問の声が浮く）
#   → batch01・batch02 の12問は完了。残り26問も同じ Daniel 指定で録る。
# ・★聞き取り検証だけで判断しない★
#   上の「話者分離の検証結果」に書いたとおり、聞き取り検証ツールは
#   根拠なく「同じ声」と報告することがある。
#   scripts/verify_q2_tts_speakers.py で数値を測り、
#   ナレーターの正答率が 80% 以上あることを確かめること。
VOICE_NARRATOR = 'Daniel'

# 役割の日本語 → 性別。部分一致で判定する。
FEMALE_WORDS = ('女性', '母親', '母', '娘', '女子', '女の子')
MALE_WORDS = ('男性', '父親', '父', '息子', '男子', '男の子')


def gender_of(role: str) -> str:
    """
    役割の日本語から 'F' / 'M' を返す。

    どちらとも判定できない場合は例外を投げる。
    黙ってどちらかに寄せると、母親が男の声で話すような
    嘘の音源ができてしまうため、必ず気付けるようにする。
    """
    for w in FEMALE_WORDS:
        if w in role:
            return 'F'
    for w in MALE_WORDS:
        if w in role:
            return 'M'
    raise ValueError(f'役割から性別を判定できません: {role!r}')


def voice_of(role: str) -> str:
    """役割に対応する声の名前を返す。"""
    return VOICE_FEMALE if gender_of(role) == 'F' else VOICE_MALE


def speakers_for(voice_map: dict[str, str]) -> list[dict[str, str]]:
    """
    manifest.json の voiceMap から、TTS へ渡す speakers 指定を組む。

    戻り値の例:
      [{'speaker': 'Speaker 1', 'voice_name': 'Adeline'},
       {'speaker': 'Speaker 2', 'voice_name': 'Mark'},
       {'speaker': 'Speaker 3', 'voice_name': 'Sam'}]

    Speaker 3 は必ずナレーター。対話が2人なので、
    voice_map には Speaker 1 と Speaker 2 だけが入っている。
    """
    out: list[dict[str, str]] = []
    for spk, role in voice_map.items():
        out.append({'speaker': spk, 'voice_name': voice_of(role)})
    out.append({'speaker': 'Speaker 3', 'voice_name': VOICE_NARRATOR})
    return out


def describe(voice_map: dict[str, str]) -> str:
    """人が読んで確認するための1行表示。"""
    parts = [f'{spk}={voice_of(role)}({role})' for spk, role in voice_map.items()]
    parts.append(f'Speaker 3={VOICE_NARRATOR}(ナレーター)')
    return ' / '.join(parts)


if __name__ == '__main__':
    # manifest 全問について、声が確定できるかを事前に検査する。
    import json
    from pathlib import Path

    root = Path(__file__).resolve().parent.parent
    manifest = json.loads(
        (root / 'scripts' / 'data' / 'q2_tts' / 'manifest.json').read_text(
            encoding='utf-8'
        )
    )
    ng = 0
    for r in manifest:
        try:
            print(f'{r["name"]}: {describe(r["voiceMap"])}')
        except ValueError as e:
            ng += 1
            print(f'{r["name"]}: ★判定不能★ {e}')
    print(f'\n合計 {len(manifest)} 問 / 判定不能 {ng} 問')
    raise SystemExit(1 if ng else 0)


