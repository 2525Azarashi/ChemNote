/**
 * 分野名 -> chapterId 用のASCIIスラッグ。
 * Firestore のドキュメントIDやTSファイル内での可読性を考え、
 * chapterId には日本語をそのまま使わずスラッグを用いる。
 * （geo-export.js の書き出しもこの表を参照する）
 */
window.GEO_MOBILE_FIELD_SLUG = {
  '地図・GIS': 'map-gis',
  '気候・植生': 'climate-vegetation',
  '地形・災害': 'landform-hazard',
  '資源・エネルギー': 'resource-energy',
  '農業・食料': 'agriculture-food',
  '人口・都市': 'population-city',
  '民族・宗教・国際': 'ethnic-religion-world',
};

/** 分野名からスラッグを引く（未知の分野は other にフォールバック） */
window.GEO_MOBILE_SLUG_OF = function (field) {
  return window.GEO_MOBILE_FIELD_SLUG[field] || 'other';
};

/**
 * アプリの pool.geography.generated.ts と同じタプルに変換する。
 * chapterId / problemId は分野とIDから機械的に作っている。
 */
window.GEO_MOBILE_TO_TUPLE = function (q) {
  return [
    q.id,                    // 0 id
    'geo-' + window.GEO_MOBILE_SLUG_OF(q.field), // 1 chapterId
    q.id,                    // 2 problemId
    q.id,                    // 3 subQuestionId
    0,                       // 4 format: choice4
    q.prompt || '',          // 5 prompt
    q.label,                 // 6 label
    q.options,               // 7 options（必ず4個）
    q.answerIndex,           // 8 answerIndex
    [],                      // 9 panelOrder（choice4では未使用）
    q.timeLimit,             // 10 timeLimit
    '',                      // 11 imageUrl
  ];
};
