function serialize(obj, indentSpaces) {
  const json = JSON.stringify(obj, null, 2);
  const pad = ' '.repeat(indentSpaces);
  return json
    .split('\n')
    .map((line, i) => (i === 0 ? pad + line : pad + line))
    .join('\n');
}

function insertBefore(src, anchor, problems) {
  const idx = src.indexOf(anchor);
  if (idx === -1) throw new Error(`anchor not found: ${anchor}`);
  // アンカー行が属するオブジェクトの開始 "{" までさかのぼる
  const objStart = src.lastIndexOf('{', idx);
  if (objStart === -1) throw new Error(`object start not found for: ${anchor}`);
  const block = problems.map((p) => serialize(p, 12)).join(',\n') + ',\n';
  // objStart の直前のインデント（12スペース）を保つ
  const lineStart = src.lastIndexOf('\n', objStart) + 1;
  return src.slice(0, lineStart) + block + src.slice(lineStart);
}

function insertAfterProblem(src, anchorId, problems) {
  const idx = src.indexOf(`"id": "${anchorId}",`);
  if (idx === -1) throw new Error(`anchor id not found: ${anchorId}`);
  // 当該問題オブジェクトの終端（"deepDiveTopics": [] のあとの "}"）を探す
  const dd = src.indexOf('"deepDiveTopics": []', idx);
  if (dd === -1) throw new Error(`deepDiveTopics not found after: ${anchorId}`);
  const close = src.indexOf('\n            }', dd);
  if (close === -1) throw new Error(`closing brace not found after: ${anchorId}`);
  const insertPos = close + '\n            }'.length;
  const block = ',\n' + problems.map((p) => serialize(p, 12)).join(',\n');
  return src.slice(0, insertPos) + block + src.slice(insertPos);
}

