def rename_category(category: str) -> str:
    """'基礎問ドリル №12 …' → 'マナトビ基本演習 Step 12 <独自題名>'"""
    import re
    m = re.match(r'基礎問ドリル №(\d+)', category)
    if not m:
        return category
    n = int(m.group(1))
    return f'{SERIES} Step {n} {TITLES[n]}'

def rephrase(text: str) -> str:
    for old, new in PHRASES:
        text = text.replace(old, new)
    return text

def apply(category: str, text: str):
    if not category.startswith('基礎問ドリル'):
        return category, text
    return rename_category(category), rephrase(text)
