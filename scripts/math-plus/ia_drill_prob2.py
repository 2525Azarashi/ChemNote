def _route_prob():
    routes = set(itertools.permutations('RRRRU'))
    def seq(p):
        x_ = y_ = 0; s_ = [(0, 0)]
        for ch in p:
            if ch == 'R': x_ += 1
            else: y_ += 1
            s_.append((x_, y_))
        return s_
    thr = [p for p in routes if (3, 1) in seq(p)]
    def pr(p):
        x_ = y_ = 0; v = F(1)
        for ch in p:
            if x_ < 4 and y_ < 1: v *= F(1, 2)
            if ch == 'R': x_ += 1
            else: y_ += 1
        return v
    return F(len(thr), len(routes)), sum(pr(p) for p in thr)
_rp1, _rp2 = _route_prob()
