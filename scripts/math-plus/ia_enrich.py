def _mean(xs): return Fr(sum(xs), len(xs))
def _var(xs):
    m_ = _mean(xs); return Fr(sum((Fr(v) - m_)**2 for v in xs), len(xs))
def _cov(xs, ys):
    mx, my = _mean(xs), _mean(ys); return Fr(sum((Fr(a_) - mx)*(Fr(b_) - my) for a_, b_ in zip(xs, ys)), len(xs))
def _q(xs):
    """四分位数（教科書方式：中央値で上下に分け、各半分の中央値）"""
    s_ = sorted(xs); n_ = len(s_)
    def med(v): 
        k_ = len(v); return Fr(v[k_//2]) if k_ % 2 else Fr(v[k_//2-1] + v[k_//2], 2)
    lo = s_[:n_//2]; hi = s_[(n_+1)//2:]
    return med(lo), med(s_), med(hi)
