def _balls(draw, pick, cond):
    # bag: list of colors; draw pick balls simultaneously
    cnt=0; tot=0
    for c in combinations(range(len(draw)), pick):
        tot+=1
        if cond([draw[i] for i in c]): cnt+=1
    return Fr(cnt,tot)
