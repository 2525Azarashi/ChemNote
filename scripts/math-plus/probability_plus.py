def _circ_adj():
    # 大人3子ども3の円順列で子どもが隣り合わない
    people=['A1','A2','A3','c1','c2','c3']
    cnt=0
    for p in permutations(people):
        if p[0]!='A1': continue  # fix A1 at seat 0
        ok=all(not(p[i][0]=='c' and p[(i+1)%6][0]=='c') for i in range(6))
        if ok: cnt+=1
    return cnt
def _circ_adj2():
    people=['A1','A2','A3','c1','c2','c3']
    cnt=0
    for p in permutations(people):
        if p[0]!='A1': continue
        if any(p[i]=='c1' and p[(i+1)%6]=='c2' or p[i]=='c2' and p[(i+1)%6]=='c1' for i in range(6)): cnt+=1
    return cnt

