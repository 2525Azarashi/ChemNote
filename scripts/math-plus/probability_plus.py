def _paths(w,h,forbid=None):
    from functools import lru_cache
    @lru_cache(None)
    def f(i,j):
        if forbid and (i,j) in forbid: return 0
        if i==0 and j==0: return 1
        s=0
        if i>0: s+=f(i-1,j)
        if j>0: s+=f(i,j-1)
        return s
    return f(w,h)

