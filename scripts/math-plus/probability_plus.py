def _walk_dice():
    # 点 P: 1,2 → +2, 3,4,5 → +1, 6 → -1. 3 回後の位置
    from collections import Counter
    cnt=Counter()
    for d in product(range(1,7),repeat=3):
        pos=sum(2 if v<=2 else (1 if v<=5 else -1) for v in d)
        cnt[pos]+=1
    return cnt

