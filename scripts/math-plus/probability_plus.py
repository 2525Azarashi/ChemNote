def _cnt_pc1():
    # 男4女3から4人選ぶ、男女とも1人以上
    people = ['M1','M2','M3','M4','F1','F2','F3']
    return sum(1 for c in combinations(people,4) if any(p[0]=='M' for p in c) and any(p[0]=='F' for p in c))
def _cnt_pc2():
    # 7人から委員長・副委員長・書記
    return perm(7,3)
def _cnt_pc3():
    # 0〜5 の6枚から3桁の整数（0が先頭不可）
    return sum(1 for p in permutations(range(6),3) if p[0]!=0)
def _cnt_pc4():
    # 3桁の偶数
    return sum(1 for p in permutations(range(6),3) if p[0]!=0 and p[2]%2==0)

