def _series(pA, need, maxgames):
    # probability A wins first-to-`need` series
    from functools import lru_cache
    @lru_cache(None)
    def f(wa,wb):
        if wa==need: return Fr(1)
        if wb==need: return Fr(0)
        return pA*f(wa+1,wb)+(1-pA)*f(wa,wb+1)
    return f(0,0)

