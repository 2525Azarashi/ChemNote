def _menelaus_ratio():
    from sympy import Matrix as _M
    A_=_M([0,0]); B_=_M([6,0]); C_=_M([1,4])
    M_=(A_+B_)/2; N_=(2*A_+C_)/3
    sol=solve(list(B_+s_*(N_-B_)-(C_+t_*(M_-C_))),[s_,t_]); P_=B_+sol[s_]*(N_-B_)
    return simplify((P_-B_).norm()/(N_-P_).norm())
s_, t_ = symbols('s_ t_')

