def _med(a):
    a = sorted(a); n = len(a)
    return F(a[n // 2]) if n % 2 else F(a[n // 2 - 1] + a[n // 2], 2)


def _quart(xs):
    s = sorted(xs); n = len(s)
    return _med(s[:n // 2]), _med(s), _med(s[(n + 1) // 2:])


def _mv(d):
    m = F(sum(d), len(d))
    return m, sum((v - m) ** 2 for v in d) / len(d)


def _rank_class(freq, lo, w, k):
    """度数分布で小さい方から k 番目が入る階級の左端"""
    c = 0
    for i, f in enumerate(freq):
        c += f
        if k <= c:
            return lo + w * i


def _dec(s):
    return F(s)


