def _cov(xs, ys):
    mx, my = Fr(sum(xs), len(xs)), Fr(sum(ys), len(ys))
    return Fr(sum((Fr(u)-mx)*(Fr(v)-my) for u, v in zip(xs, ys)), len(xs))
def _corr(xs, ys):
    return _cov(xs, ys) / (sqrt(_cov(xs,xs)) * sqrt(_cov(ys,ys)))
