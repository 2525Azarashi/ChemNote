def _pf(n_):
    d, out = 2, {}
    while d*d <= n_:
        while n_ % d == 0: out[d] = out.get(d,0)+1; n_ //= d
        d += 1
    if n_ > 1: out[n_] = out.get(n_,0)+1
    return out
