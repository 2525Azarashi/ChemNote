def _mv(d):
    m = F(sum(d), len(d))
    return m, sum((v - m) ** 2 for v in d) / len(d)


def _cov(x_, y_):
    mx, my = F(sum(x_), len(x_)), F(sum(y_), len(y_))
    return sum((a - mx) * (b - my) for a, b in zip(x_, y_)) / len(x_)


