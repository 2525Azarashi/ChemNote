def _right(t):
    for i in range(3):
        a_, b_, c_ = [_pts[t[(i + j) % 3]] for j in range(3)]
        if abs((b_[0]-a_[0])*(c_[0]-a_[0]) + (b_[1]-a_[1])*(c_[1]-a_[1])) < 1e-9:
            return True
    return False
