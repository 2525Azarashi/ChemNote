def _paths(W, H, blocked=frozenset()):
    dp = {}
    for x_ in range(W + 1):
        for y_ in range(H + 1):
            if x_ == 0 and y_ == 0:
                dp[(0, 0)] = 1
                continue
            v = 0
            if x_ > 0 and ((x_-1, y_), (x_, y_)) not in blocked: v += dp[(x_-1, y_)]
            if y_ > 0 and ((x_, y_-1), (x_, y_)) not in blocked: v += dp[(x_, y_-1)]
            dp[(x_, y_)] = v
    return dp[(W, H)]
