/**
 * ===================================================================
 * updateNotices.ts ― アプリの更新履歴（お知らせ）
 * ===================================================================
 *
 * ■ 何のファイルか
 *   「何がいつ変わったのか」を利用者が自分で確認できるようにするための台帳。
 *   アプリを更新しても、利用者から見ると画面が黙って変わるだけで、
 *   直った不具合にも増えた問題にも気づけない。
 *   その結果「前は解けたのに」「問題が増えたのを知らなかった」という
 *   もったいない状態が生まれるため、更新内容を明示する。
 *
 * ■ なぜ Firestore ではなくコードに持つのか
 *   ・更新内容はアプリのバージョンと1対1で決まるので、
 *     配信物（ビルド）と同じ場所にある方が食い違わない
 *   ・通信不要で必ず表示できる（オフラインでも読める）
 *   ・運営が管理画面を触らずに、コードの1か所を足すだけで済む
 *
 * ■ 追加のしかた（運営向け・ここだけ守れば良い）
 *   1. UPDATE_NOTICES の**先頭**に1件足す（新しいものが上）
 *   2. id は 'YYYY-MM-DD-連番' の形にする（重複しない・並べ替えても壊れない）
 *   3. date は 'YYYY-MM-DD'、time は 'HH:MM'（日時まで出すご要望に対応）
 *   4. items は「利用者が得する言い方」で1〜4行。内部用語は書かない
 *      ×「ListeningAudioPlayer に focusSubId を追加」
 *      ○「リスニングで、問ごとに再生ボタンを置きました」
 *
 * ■ 未読の判定
 *   「最後に開いたときの最新ID」を localStorage に持ち、
 *   それより新しい件数をバッジに出す（utils/updateNotices.ts）。
 *   アカウントに紐づけないので、ログインしていなくても機能する。
 */

/** お知らせ1件の種別。バッジの色と文言に使う。 */
export type UpdateNoticeKind = 'feature' | 'content' | 'fix' | 'improve';

export interface UpdateNotice {
  /** 一意なID。'YYYY-MM-DD-連番' 形式 */
  id: string;
  /** 更新日（YYYY-MM-DD） */
  date: string;
  /** 更新時刻（HH:MM）。時刻まで出したいというご要望に対応する */
  time: string;
  /** 種別（新機能 / 問題追加 / 不具合修正 / 改善） */
  kind: UpdateNoticeKind;
  /** 1行の見出し。これだけ読めば何が変わったか分かるように書く */
  title: string;
  /** 箇条書きの詳細（1〜4行程度） */
  items: string[];
}

