/**
 * ===================================================================
 * 「化学」（発展／理論・無機・有機）の単元データ
 * ===================================================================
 *
 * 位置づけ
 *  - 既存の `chemistryData.ts`（化学基礎）と **まったく同じ形** の
 *    parts / chapters 構造を持つ。これにより、単元選択画面をはじめ
 *    既存コンポーネントをそのまま流用できる。
 *
 * 構造の対応（化学基礎と同じルール）
 *  - `parts[].title`        … 大きな区分。化学では「理論化学／無機化学／有機化学」
 *  - `chapters[].realTitle` … 教科書の「章」。単元選択画面のタブになる
 *  - `chapters[].abstractTitle`
 *                           … 教科書の「小単元」。アプリ上の1単元（＝大問の集まり）
 *  - `chapters[].topics`    … その小単元で扱う内容の要約
 *  - `chapters[].practiceProblems` / `miniTest`
 *                           … 問題本体。収録済みの単元は末尾の `ADVANCED_PROBLEMS`
 *                              で章IDをキーに流し込む（未収録の単元は空配列のまま）
 *
 * 並び順の方針
 *  - ユーザー指示により「ひとまず教科書順」とする。
 *    数研出版『化学』の配列（物質の状態 → 物質の変化と平衡 → 無機 → 有機 → 高分子）
 *    に沿って章を並べ、章内の小単元も教科書の節の順に並べている。
 *  - 学習順の最適化（例：先に有機をやる等）は行っていない。
 *    並べ替えが必要になった場合、この配列の順序を入れ替えるだけで反映される。
 *
 * ID 規約
 *  - 化学基礎の `c1_1` 形式と衝突しないよう、すべて `a`（advanced）接頭辞を付ける。
 *    例）`a1_1` = 化学・1章・小単元1
 *  - 進捗・ランキングは章IDをキーに保存されるため、
 *    接頭辞を分けることで化学基礎の既存データを一切汚染しない。
 */

