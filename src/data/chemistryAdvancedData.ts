/** 1つの小単元（アプリ上の1単元＝大問の集まり）。化学基礎の chapter と同形。 */
export interface AdvancedChapter {
  id: string;
  /** 教科書の小単元名（アプリの単元名として表示） */
  abstractTitle: string;
  /** 教科書の章名（単元選択画面のタブ見出しになる） */
  realTitle: string;
  /** 扱う内容 */
  topics: string[];
  /** 演習問題（収録済みの単元は ADVANCED_PROBLEMS から流し込まれる） */
  practiceProblems: any[];
  /** 小テスト（現時点では未収録） */
  miniTest: any[];
}

export interface AdvancedPart {
  id: string;
  title: string;
  /** 分野の識別子（理論／無機／有機の絞り込みに使う） */
  field: 'theoretical' | 'inorganic' | 'organic';
  chapters: AdvancedChapter[];
}

